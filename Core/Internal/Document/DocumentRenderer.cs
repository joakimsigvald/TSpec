using System.Text;
using TSpec.Internal.Specification;

namespace TSpec.Internal.Document;

/// <summary>
/// Renders the specification document. Each entry's steps are rendered here rather than arriving as
/// finished text, so the document can lay them out its own way; what comes back has platform-native
/// line endings and is normalized to LF, since a Windows run would otherwise commit a file that
/// differs from a Linux one on every line. That plus full sorting makes the document byte-identical
/// on every machine, which is what lets its diff be reviewed.
/// </summary>
internal static class DocumentRenderer
{
    internal static string Render(
        SpecificationSubject subject, string specAssemblyName, string buildId,
        IEnumerable<SpecificationEntry> entries)
    {
        // Version and build id are provenance: they answer "which build produced this" for a diff
        // or a pipeline, never a question a reader of requirements has. Kept in the generated-file
        // comment, they stay in the file — and in its diff — without occupying the page.
        var text = new StringBuilder()
            .Append($"# {subject.Name.AsTitle()}\n\n")
            .Append($"<!-- Version {subject.Version}+{buildId}, ")
            .Append($"generated by TSpec from {specAssemblyName}. Do not edit by hand. -->\n");

        var requirements = Ordered(entries).ToArray();
        var whole = SharedOpening(requirements);
        if (whole.Count > 0)
            text.Append(Block(Render(whole, because: null)));

        foreach (var group in requirements.Select(r => r.Without(whole.Count)).GroupBy(r => r.Entry.Subject))
        {
            var ofSubject = group.ToArray();
            var shared = SharedOpening(ofSubject);
            text.Append($"\n## {group.Key.AsHeading()}\n");
            if (shared.Count > 0)
                text.Append(Block(Render(shared, because: null)));

            foreach (var branch in ofSubject
                .Select(r => r.Without(shared.Count))
                .GroupBy(r => r.Entry.Branch))
            {
                var ofBranch = branch.ToArray();
                // Without a branch heading there is nothing for a shared opening to be stated under.
                var condition = branch.Key.Length > 0 ? SharedOpening(ofBranch) : [];
                if (branch.Key.Length > 0)
                {
                    text.Append($"\n### {branch.Key.AsHeading()}\n");
                    if (condition.Count > 0)
                        text.Append(Block(Render(condition, because: null)));
                }
                foreach (var requirement in ofBranch.Select(r => r.Without(condition.Count)))
                    text.Append($"\n{RequirementHeading(branch.Key)} {requirement.Entry.Requirement.AsHeading()}\n"
                        + Block(Render(requirement.Clauses, requirement.Entry.Because)));
            }
        }
        return text.ToString();
    }

    /// <summary>
    /// The clauses every requirement here opens with — stated once under the heading instead of
    /// repeated in each block. Whole clauses only, never a fragment of one, and no minimum number of
    /// requirements: a lone one still belongs under the heading that names its context.
    /// </summary>
    /// <remarks>
    /// Assertions are excluded on principle, and it is that exclusion rather than any counting rule
    /// that keeps a block from being hollowed out: they are the claim each requirement exists to
    /// make, so two requirements agreeing on one is a coincidence to leave visible, not repetition
    /// to factor out. Arrangement and action are context, and context is what a heading is for.
    /// A leading "and ..." can never be left behind, because lead words are assigned while
    /// rendering — whatever clause a block now opens with is given its family's word.
    /// </remarks>
    private static IReadOnlyList<SpecificationClause> SharedOpening(Requirement[] requirements)
    {
        if (requirements.Length == 0)
            return [];

        var first = requirements[0].Clauses;
        // Hoisting must never empty a block, so the shortest requirement always keeps one clause.
        var limit = requirements.Min(requirement => requirement.Clauses.Count) - 1;
        var shared = 0;
        while (shared < limit
            && first[shared].Phase != StepPhase.Assert
            && requirements.All(requirement => requirement.Clauses[shared].Matches(first[shared])))
            shared++;

        return [.. first.Take(shared)];
    }

    /// Rendered up front because identity is the rendered text: a theory reports once per case, and
    /// cases differing only in generated values describe one and the same requirement.
    private static IEnumerable<Requirement> Ordered(IEnumerable<SpecificationEntry> entries)
        => entries
            .Select(entry => (Entry: entry, Specification: Render(entry)))
            .DistinctBy(requirement => (
                requirement.Entry.Subject,
                requirement.Entry.Branch,
                requirement.Entry.Requirement,
                requirement.Specification))
            .OrderBy(requirement => requirement.Entry.Subject, StringComparer.Ordinal)
            .ThenBy(requirement => requirement.Entry.Branch, StringComparer.Ordinal)
            .ThenBy(requirement => requirement.Entry.Requirement, StringComparer.Ordinal)
            .Select(requirement => new Requirement(
                requirement.Entry, SpecificationClause.Split(requirement.Entry.Steps)));

    private static string Render(SpecificationEntry entry)
        => Render(SpecificationClause.Split(entry.Steps), entry.Because);

    private static string Render(IReadOnlyList<SpecificationClause> clauses, string? because)
        => SpecificationRenderer
            .Render(clauses.SelectMany(clause => clause.Steps), because, new TextBuilder())
            .NormalizeLineEndings();

    /// No blank line before the fence: a heading and an HTML comment are both leaf blocks that end
    /// at their own line, so the fence opens correctly either way and the blank line renders as
    /// nothing at all.
    private static string Block(string specification) => $"```\n{specification}\n```\n";

    /// A requirement sits under its branch when it has one. A subject with no branches has nothing
    /// to nest under, so its requirements stay a level up rather than skipping a heading level.
    private static string RequirementHeading(string branch) => branch.Length == 0 ? "###" : "####";

    /// One requirement with its specification broken into clauses, as hoisting consumes them.
    private sealed record Requirement(SpecificationEntry Entry, IReadOnlyList<SpecificationClause> Clauses)
    {
        internal Requirement Without(int hoisted)
            => hoisted == 0 ? this : this with { Clauses = [.. Clauses.Skip(hoisted)] };
    }
}
