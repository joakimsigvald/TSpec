using System.Text;
using TSpec.Internal.Specification;
using static TSpec.Internal.Document.DocumentText;

namespace TSpec.Internal.Document;

/// <summary>
/// Renders a specification document from test-specification. 
/// Line endings normalized to LF for platform independence.
/// Normalized and organized to make equivalent specs byte-identical
/// on every machine, allowing for automated diff-detection.
/// </summary>
internal class DocumentRenderer
{
    internal static string Render(
        SpecificationSubject subject, string specAssemblyName, string buildId,
        IEnumerable<SpecificationEntry> entries)
    {
        Document doc = Document.Of(subject, specAssemblyName, buildId, entries);
        DocumentRenderer renderer = new(doc);
        renderer.AppendTitle();
        renderer.AppendContent();
        return renderer.ToString();
    }

    private readonly Document _document;
    private readonly StringBuilder _text = new();

    private DocumentRenderer(Document document) => _document = document;

    public override string ToString() => _text.ToString();

    private StringBuilder Append(string? text) => _text.Append(text);

    private void AppendTitle()
        => Append($"# {_document.Subject.Name.AsTitle()}\n\n")
            .Append($"<!-- Version {_document.Subject.Version}+{_document.BuildId}, ")
            .Append($"generated by TSpec from {_document.SpecAssemblyName}. Do not edit by hand. -->\n");

    private void AppendContent()
    {
        Append(HeadingStatement.Says(_document.Declared, _document.Whole, stated: null));
        if (_document.Areas.Count > 0)
            AppendRequirements();
    }

    private void AppendRequirements()
    {
        Append("\n---\n");
        foreach (var area in Order(_document.Areas))
            AppendNode(area, _document.Declared);
    }

    /// <summary>
    /// A node, then whatever runs below it. <paramref name="stated"/> is everything the headings
    /// above have already declared, so each heading states only what is new at it.
    /// </summary>
    private void AppendNode(DocumentNode node, Declared stated)
    {
        if (node.Heading is not null)
            Append(HeadingStatement.Heading(
                node.Level, node.Heading, node.Declaration.Except(stated), node.Shared));

        if (node is BranchNode branch)
            AppendLeaves(branch);
        else
            foreach (var section in Order(node.Children))
                AppendNode(section, stated.And(node.Declaration));
    }

    private void AppendLeaves(BranchNode branch)
    {
        Append("\n");
        foreach (var requirement in InReadingOrder(branch.Requirements))
            Append(Leaf(requirement));
    }

    /// <summary>
    /// The requirements of a branch as they read best: least arranged first, then shortest, so a
    /// reader meets preconditions gradually. Ties fall back to names, which are stable.
    /// </summary>
    private static IEnumerable<Requirement> InReadingOrder(IReadOnlyList<Requirement> requirements)
        => requirements
            .OrderBy(requirement => requirement.Arrangement)
            .ThenBy(requirement => Fit(
                Compose(requirement.Clauses, requirement.Entry.Because), DocumentWidth).Length)
            .ThenBy(requirement => requirement.Entry.Requirement, StringComparer.Ordinal)
            .ThenBy(requirement => requirement.Signature, StringComparer.Ordinal);

    /// <summary>
    /// Sections in the order they read: whatever heads nothing first, so its content is not
    /// swallowed by the heading before it, then simplest first, then by name.
    /// </summary>
    private static DocumentNode[] Order(IEnumerable<DocumentNode> nodes)
        => [..nodes.OrderBy(node => node.HasKey)
            .ThenBy(node => node.ComplexityNumber)
            .ThenBy(node => node.Key, StringComparer.Ordinal)];

    private static string Leaf(Requirement requirement)
    {
        var name = requirement.Entry.Requirement.AsHeading();
        var label = Without(StatedWord(name), name);
        var text = Compose(requirement.Clauses, requirement.Entry.Because)
            .Without(StepFamily.Then.Keyword());
        var claim = Fit(text, ClaimWidth);
        if (claim.Contains('\n'))
            return $"- **{label}**\n{Indent($"```\n{Fit(text, FenceWidth)}\n```")}\n";

        var beside = $"- **{label}** — `{claim}`";
        return beside.Length <= DocumentWidth
            ? $"{beside}\n"
            : $"- **{label}**\\\n{Indent($"`{claim}`")}\n";
    }
}