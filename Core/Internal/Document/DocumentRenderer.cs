namespace TSpec.Internal.Document;

/// <summary>
/// Renders the specification document. Line endings are always LF, so the file is
/// byte-identical on every machine that runs the suite.
/// </summary>
internal static class DocumentRenderer
{
    internal static string Render(SpecificationSubject subject, string specAssemblyName)
        => string.Join("\n",
            $"# {subject.Name}",
            "",
            $"Version {subject.Version}",
            "",
            $"<!-- Generated by TSpec from {specAssemblyName}. Do not edit by hand. -->",
            "");
}
