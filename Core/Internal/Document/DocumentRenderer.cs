using System.Text;
using TSpec.Internal.Specification;

namespace TSpec.Internal.Document;

/// <summary>
/// Renders the specification document. Each entry's steps are rendered here rather than arriving as
/// finished text, so the document can lay them out its own way; what comes back has platform-native
/// line endings and is normalized to LF, since a Windows run would otherwise commit a file that
/// differs from a Linux one on every line. That plus full sorting makes the document byte-identical
/// on every machine, which is what lets its diff be reviewed.
/// </summary>
internal static class DocumentRenderer
{
    /// Setup that every requirement of a subject shares is stated once under the subject heading
    /// rather than repeated in each block. Below this many requirements it is not repetition worth
    /// factoring out, and the reader is better served by a block that stands alone.
    private const int SharedSetupThreshold = 3;

    internal static string Render(
        SpecificationSubject subject, string specAssemblyName, string buildId,
        IEnumerable<SpecificationEntry> entries)
    {
        var text = new StringBuilder()
            .Append($"# {subject.Name}\n\n")
            .Append($"Version {subject.Version}, hash {buildId}\n\n")
            .Append($"<!-- Generated by TSpec from {specAssemblyName}. Do not edit by hand. -->\n");
        foreach (var group in Ordered(entries).GroupBy(requirement => requirement.Entry.Subject))
        {
            var requirements = group.Select(requirement => Split(requirement.Entry)).ToArray();
            var shared = SharedSetup(requirements);
            text.Append($"\n## {group.Key}\n");
            if (shared.Count > 0)
                text.Append(Block(Render(shared, because: null)));

            foreach (var (entry, clauses) in requirements)
                text.Append($"\n### {Heading(entry)}\n"
                    + Block(Render([.. clauses.Skip(shared.Count)], entry.Because)));
        }
        return text.ToString();
    }

    /// <summary>
    /// The leading setup clauses shared by every requirement of a subject. Whole clauses only, and
    /// the whole <c>Using</c> run or none of it — hoisting part of a run would leave a headless
    /// "and ..." behind in each block.
    /// </summary>
    private static IReadOnlyList<SpecificationClause> SharedSetup(
        (SpecificationEntry Entry, IReadOnlyList<SpecificationClause> Clauses)[] requirements)
    {
        if (requirements.Length < SharedSetupThreshold)
            return [];

        var candidate = LeadingSetup(requirements[0].Clauses);
        if (candidate.Count == 0)
            return [];

        return requirements.All(requirement => Shares(requirement.Clauses, candidate)) ? candidate : [];
    }

    /// The clauses a requirement opens with, taken only when they hold every <c>Using</c> it has.
    private static IReadOnlyList<SpecificationClause> LeadingSetup(IReadOnlyList<SpecificationClause> clauses)
    {
        var leading = clauses.TakeWhile(clause => clause.Family == StepFamily.Using).ToArray();
        return clauses.Skip(leading.Length).Any(clause => clause.Family == StepFamily.Using)
            ? []
            : leading;
    }

    /// A requirement shares the setup when it opens with the same clauses and still says something
    /// of its own afterwards — hoisting must never leave a block empty.
    private static bool Shares(
        IReadOnlyList<SpecificationClause> clauses, IReadOnlyList<SpecificationClause> shared)
        => clauses.Count > shared.Count
        && LeadingSetup(clauses) is { } leading
        && leading.Count == shared.Count
        && leading.Zip(shared).All(pair => pair.First.Matches(pair.Second));

    /// Rendered up front because identity is the rendered text: a theory reports once per case, and
    /// cases differing only in generated values describe one and the same requirement.
    private static IEnumerable<(SpecificationEntry Entry, string Specification)> Ordered(
        IEnumerable<SpecificationEntry> entries)
        => entries
            .Select(entry => (Entry: entry, Specification: Render(entry)))
            .DistinctBy(requirement => (
                requirement.Entry.Subject,
                requirement.Entry.Branch,
                requirement.Entry.Requirement,
                requirement.Specification))
            .OrderBy(requirement => requirement.Entry.Subject, StringComparer.Ordinal)
            .ThenBy(requirement => requirement.Entry.Branch, StringComparer.Ordinal)
            .ThenBy(requirement => requirement.Entry.Requirement, StringComparer.Ordinal);

    private static (SpecificationEntry Entry, IReadOnlyList<SpecificationClause> Clauses) Split(
        SpecificationEntry entry)
        => (entry, SpecificationClause.Split(entry.Steps));

    private static string Render(SpecificationEntry entry)
        => Render(SpecificationClause.Split(entry.Steps), entry.Because);

    private static string Render(IReadOnlyList<SpecificationClause> clauses, string? because)
        => SpecificationRenderer
            .Render(clauses.SelectMany(clause => clause.Steps), because, new TextBuilder())
            .NormalizeLineEndings();

    private static string Block(string specification) => $"\n```\n{specification}\n```\n";

    private static string Heading(SpecificationEntry entry)
        => entry.Branch.Length == 0 ? entry.Requirement : $"{entry.Branch}.{entry.Requirement}";
}
