using System.Text;
using TSpec.Internal.Specification;

namespace TSpec.Internal.Document;

/// <summary>
/// Renders the specification document. Each entry's steps are rendered here rather than arriving as
/// finished text, so the document can lay them out its own way; what comes back has platform-native
/// line endings and is normalized to LF, since a Windows run would otherwise commit a file that
/// differs from a Linux one on every line. That plus full sorting makes the document byte-identical
/// on every machine, which is what lets its diff be reviewed.
/// </summary>
internal static class DocumentRenderer
{
    internal static string Render(
        SpecificationSubject subject, string specAssemblyName, string buildId,
        IEnumerable<SpecificationEntry> entries)
    {
        var text = new StringBuilder()
            .Append($"# {subject.Name.AsTitle()}\n\n")
            .Append($"<!-- Version {subject.Version}+{buildId}, ")
            .Append($"generated by TSpec from {specAssemblyName}. Do not edit by hand. -->\n");

        var requirements = Distinct(entries).ToArray();
        var declared = Declaration(requirements, returns: false);
        var whole = SharedClauses(requirements, acts: false);
        text.Append(HeadingBlock(declared, whole, stated: null));
        // An area heads at the title's own level, there being none above it, so a rule closes what
        // the document says of itself — without one the first area would read as a sibling of the
        // title. It belongs under that block rather than under the title alone, which would put a
        // rule between two things that are one: the document's name and what holds throughout it.
        if (requirements.Length > 0)
            text.Append("\n---\n");

        foreach (var area in Areas(requirements, whole))
        {
            if (area.Key.Length > 0)
                text.Append(Heading(1, area.Key.AsHeading(), area.Declaration.Except(declared), area.Shared));

            // One group under an area is the area over again, so it heads nothing and costs no
            // level; several are what the area does not say, and each heads its own.
            var grouped = area.Groups.Length > 1;
            foreach (var group in area.Groups)
            {
                if (grouped)
                    text.Append(Heading(2, group.Key.AsTitle(),
                        group.Declaration.Except(declared).Except(area.Declaration), group.Shared));

                foreach (var subjectNode in group.Subjects)
                {
                    text.Append(Heading(grouped ? 3 : 2, subjectNode.Key.AsHeading(),
                        subjectNode.Declaration.Except(declared).Except(area.Declaration)
                            .Except(group.Declaration),
                        subjectNode.Shared));

                    foreach (var branch in subjectNode.Branches)
                    {
                        if (branch.Key.Length > 0)
                            text.Append(Heading(grouped ? 4 : 3, branch.Key.AsHeading(), default, branch.Shared));
                        text.Append('\n');
                        foreach (var requirement in branch.Requirements)
                            text.Append(Leaf(requirement));
                    }
                }
            }
        }
        return text.ToString();
    }

    /// A heading at its level, followed by whatever the level below no longer has to say.
    private static string Heading(
        int level, string heading, Declared declared, IReadOnlyList<SpecificationClause> shared)
        => $"\n{new string('#', level)} {heading}\n"
            + HeadingBlock(declared, shared, StatedWord(heading));

    /// <summary>
    /// The areas of the system — one per namespace segment the specs differ in, which is the folder
    /// they were written in. Specs at the shared root belong to no area and keep the title as their
    /// heading, so that key comes first; the rest are ordered the way subjects are.
    /// </summary>
    private static IEnumerable<AreaNode> Areas(
        Requirement[] requirements, IReadOnlyList<SpecificationClause> hoisted)
    {
        var root = SharedRoot(requirements);
        return requirements
            .Select(requirement => requirement.Without(hoisted))
            .GroupBy(requirement => Area(requirement.Entry.Namespace, root))
            .Select(area => ToArea(area, root))
            .OrderBy(area => area.Key.Length == 0 ? 0 : 1)
            .ThenBy(area => area.ComplexityNumber)
            .ThenBy(area => area.Key, StringComparer.Ordinal);
    }

    /// <summary>
    /// How many leading namespace segments every spec in the document shares. Below that is where
    /// they differ, and the segment right below it names an area — so a document whose specs share
    /// one namespace has no areas at all, which is the right answer twice over: nothing to tell
    /// apart, and a heading spanning everything states nothing.
    /// </summary>
    private static int SharedRoot(Requirement[] requirements)
    {
        var paths = requirements.Select(requirement => Segments(requirement.Entry.Namespace)).ToArray();
        if (paths.Length == 0)
            return 0;

        var shared = paths[0].Length;
        foreach (var path in paths)
        {
            var common = 0;
            while (common < shared && common < path.Length && path[common] == paths[0][common])
                common++;
            shared = common;
        }
        return shared;
    }

    /// The area a spec belongs to: the first namespace segment below the shared root.
    private static string Area(string? @namespace, int root)
    {
        var segments = Segments(@namespace);
        return segments.Length > root ? segments[root] : string.Empty;
    }

    /// <summary>
    /// The group a spec belongs to within its area: everything left of its namespace below the
    /// area, as one dotted key. Merged rather than nested a segment at a time — the levels a
    /// document can tell apart are nearly spent by the area, and what is left names one thing.
    /// </summary>
    private static string Group(string? @namespace, int root)
        => string.Join('.', Segments(@namespace).Skip(root + 1));

    private static string[] Segments(string? @namespace)
        => @namespace?.Split('.', StringSplitOptions.RemoveEmptyEntries) ?? [];

    /// <summary>
    /// The subjects of one area, simplest first. A node's <c>ComplexityNumber</c> is the arrangement
    /// stated at its own heading plus that of everything under it, so a reader meets preconditions
    /// gradually rather than all at once — and ties fall back to the name, which is stable.
    /// </summary>
    /// <remarks>
    /// Assertions are not counted, and that is what makes summing upward safe: adding a requirement
    /// to an existing branch changes no number anywhere in the tree, so no section moves. Only
    /// arrangement appearing or disappearing can reorder the document, which is a structural change
    /// worth seeing in the diff. Counting size instead would reshuffle whole subjects because one
    /// line was added, spending the very thing the document is reviewed for.
    /// </remarks>
    private static AreaNode ToArea(IGrouping<string, Requirement> area, int root)
    {
        var ofArea = area.ToArray();
        // Without an area heading there is nothing for what it would state to be stated under.
        var shared = area.Key.Length > 0 ? SharedClauses(ofArea, acts: false) : [];
        var declared = area.Key.Length > 0 ? Declaration(ofArea, returns: false) : default;
        var groups = ofArea
            .Select(requirement => requirement.Without(shared))
            .GroupBy(requirement => Group(requirement.Entry.Namespace, root))
            .ToArray();
        return new(area.Key, shared, declared, [.. groups
            .Select(group => ToGroup(group, heads: groups.Length > 1))
            .OrderBy(group => group.ComplexityNumber)
            .ThenBy(group => group.Key, StringComparer.Ordinal)]);
    }

    /// <summary>
    /// One group of an area and the subjects under it. A lone group heads nothing — the area above
    /// it already divides exactly what it would — so it states nothing of its own either, there
    /// being no heading for that to be stated under.
    /// </summary>
    private static GroupNode ToGroup(IGrouping<string, Requirement> group, bool heads)
    {
        var ofGroup = group.ToArray();
        var shared = heads ? SharedClauses(ofGroup, acts: false) : [];
        var declared = heads ? Declaration(ofGroup, returns: false) : default;
        return new(group.Key, shared, declared, [.. ofGroup
            .Select(requirement => requirement.Without(shared))
            .GroupBy(requirement => requirement.Entry.Subject)
            .Select(ToSubject)
            .OrderBy(subject => subject.ComplexityNumber)
            .ThenBy(subject => subject.Key, StringComparer.Ordinal)]);
    }

    private static SubjectNode ToSubject(IGrouping<string, Requirement> group)
    {
        var ofSubject = group.ToArray();
        var shared = SharedClauses(ofSubject);
        return new(group.Key, shared, Declaration(ofSubject), [.. ofSubject
            .Select(requirement => requirement.Without(shared))
            .GroupBy(requirement => requirement.Entry.Branch)
            .Select(ToBranch)
            .OrderBy(branch => branch.ComplexityNumber)
            .ThenBy(branch => branch.Key, StringComparer.Ordinal)]);
    }

    private static BranchNode ToBranch(IGrouping<string, Requirement> group)
    {
        var ofBranch = group.ToArray();
        // Without a branch heading there is nothing for a shared opening to be stated under.
        var shared = group.Key.Length > 0 ? SharedClauses(ofBranch) : [];
        return new(group.Key, shared, [.. ofBranch
            .Select(requirement => requirement.Without(shared))
            .OrderBy(requirement => Arrangement(requirement.Clauses))
            .ThenBy(requirement => Render(
                Compose(requirement.Clauses, requirement.Entry.Because), DocumentWidth).Length)
            .ThenBy(requirement => requirement.Entry.Requirement, StringComparer.Ordinal)
            .ThenBy(requirement => requirement.Specification, StringComparer.Ordinal)]);
    }

    /// How much a heading's own clauses arrange, which is every phase but the claim itself.
    private static int Arrangement(IReadOnlyList<SpecificationClause> clauses)
        => clauses.Count(clause => clause.Phase != StepPhase.Assert);

    /// <summary>
    /// What a heading declares about the code it describes. Each label is carried separately, and
    /// null where the requirements below disagree and the statement belongs further down instead —
    /// a subject can hold for a whole document while every section returns something different.
    /// </summary>
    /// <remarks>
    /// Stated rather than phrased, because no one phrasing survives every spec: <c>Spec&lt;int&gt;</c>
    /// over a static calculation would read as nonsense in a sentence and reads plainly as a label.
    /// This is the document's own apparatus, like the title and the provenance comment — never a
    /// step, or it would appear in every per-test specification too. It stays out of
    /// <c>ComplexityNumber</c> for the same reason, and would cancel anyway.
    /// </remarks>
    private readonly record struct Declared(string? Subject, string? ReturnType)
    {
        internal Declared Except(Declared stated)
            => new(stated.Subject is null ? Subject : null,
                stated.ReturnType is null ? ReturnType : null);

        /// <summary>
        /// One space after each label, never a column: the two hoist independently, so aligning
        /// them would make where a value starts depend on which other label happens to be stated
        /// beside it — and a label standing alone has nothing to line up with anyway.
        /// </summary>
        internal string? Text => (Subject, ReturnType) switch
        {
            (null, null) => null,
            (not null, null) => $"{SubjectLabel} {Subject}",
            (null, not null) => ReturnLine,
            _ => $"{SubjectLabel} {Subject}\n{ReturnLine}",
        };

        /// The return type as a label of its own, for where it follows the clauses instead.
        internal string? ReturnLine => ReturnType is null ? null : $"{ReturnLabel} {ReturnType}";
    }

    /// <remarks>
    /// The return type rises only as far as the subject, for the reason the act does — the heading
    /// there is named after the method, and above it nothing is. The subject names a class rather
    /// than a call, so it carries no such tie and rises as far as it holds.
    /// </remarks>
    private static Declared Declaration(Requirement[] requirements, bool returns = true)
    {
        var first = requirements.FirstOrDefault()?.Entry;
        if (first?.SubjectUnderTest is null)
            return default;

        return new(
            requirements.All(r => r.Entry.SubjectUnderTest == first.SubjectUnderTest)
                ? first.SubjectUnderTest : null,
            returns && requirements.All(r => r.Entry.ReturnType == first.ReturnType)
                ? first.ReturnType : null);
    }

    private const string SubjectLabel = "Subject under test:";
    private const string ReturnLabel = "Return type:";

    /// The specification under a heading: what it declares, then the clauses hoisted to it. Nothing
    /// to say means nothing is written at all, so a heading never opens an empty block.
    private static string HeadingBlock(
        Declared declared, IReadOnlyList<SpecificationClause> shared, string? stated)
    {
        var above = declared with { ReturnType = null };
        var joins = declared.ReturnType is not null
            && shared.Any(clause => clause.Family == StepFamily.When)
            && Joins(above, shared, declared.ReturnType, stated);
        // Said under the clauses where it did not fit on the act: it qualifies what they say, so it
        // follows them rather than heading a block it is not part of. With no clauses to follow it
        // has only the subject to stand beside, and stays where that is.
        var trails = !joins && declared.ReturnType is not null && shared.Count > 0;
        var says = joins || trails ? above : declared;
        var clauses = shared.Count == 0
            ? null
            : Clauses(says, shared, joins ? declared.ReturnType : null, stated);
        string?[] parts = [says.Text, clauses, trails ? declared.ReturnLine : null];
        var body = string.Join("\n", parts.Where(part => !string.IsNullOrEmpty(part)));
        return body.Length == 0 ? string.Empty : Block(body);
    }

    /// <summary>
    /// Whether the return type may be said on the act, which it may only where it costs no line: a
    /// trailing phrase that wraps starts its line with the binder's comma, breaking a statement
    /// where nothing relates the halves. Where it does not fit it stays the label it already is at
    /// a heading with no act — said once either way, only in the other of its two forms.
    /// </summary>
    private static bool Joins(
        Declared says, IReadOnlyList<SpecificationClause> shared, string returns, string? stated)
        => Lines(Clauses(says, shared, returns, stated)) == Lines(Clauses(says, shared, null, stated));

    /// A label above the clauses opens the block, so the clauses keep the heading's word.
    private static string Clauses(
        Declared says, IReadOnlyList<SpecificationClause> shared, string? returns, string? stated)
        => Render(
            Compose(shared, because: null, returns).Without(says.Text is null ? stated : null),
            DocumentWidth);

    private static int Lines(string text) => text.Count(character => character == '\n');

    /// <summary>
    /// A requirement as an item of a list. It gets no heading of its own: a heading here would be a
    /// fourth level, which renders at body size and so cannot be told from the third — and writing
    /// one takes two elements whose four margins are most of the document's height. Items of a tight
    /// list have no margins between them, and being a different kind of thing from the headings above
    /// them is what lets those headings read as a hierarchy at all.
    /// </summary>
    private static string Leaf(Requirement requirement)
    {
        var name = requirement.Entry.Requirement.AsHeading();
        var label = Without(StatedWord(name), name);
        var text = Compose(requirement.Clauses, requirement.Entry.Because)
            .Without(StepFamily.Then.Keyword());
        var claim = Render(text, ClaimWidth);
        if (claim.Contains('\n'))
            return $"- **{label}**\n{Indent($"```\n{Render(text, FenceWidth)}\n```")}\n";

        // Hard break: a soft one would be reflowed away, putting back the line it broke.
        var beside = $"- **{label}** — `{claim}`";
        return beside.Length <= DocumentWidth
            ? $"{beside}\n"
            : $"- **{label}**\\\n{Indent($"`{claim}`")}\n";
    }

    /// <summary>
    /// The clauses every requirement here states — written once under the heading instead of
    /// repeated in each block. Whole clauses only, never a fragment of one, and no minimum number of
    /// requirements: a lone one still belongs under the heading that names its context.
    /// </summary>
    /// <remarks>
    /// Each clause is decided on its own, not as part of a shared opening. Position cannot be the
    /// test, because the specification is written in the order the pipeline runs — arrangement
    /// before the act — so a branch that arranges anything of its own sits in front of the
    /// <c>When</c> the whole subject shares, and a rule keyed on the opening would leave that
    /// <c>When</c> out of the very heading named after it.
    /// <para>
    /// Assertions are excluded on principle: they are the claim each requirement exists to make, so
    /// two requirements agreeing on one is a coincidence to leave visible, not repetition to factor
    /// out. Arrangement and action are context, and context is what a heading is for. The one
    /// counting rule left is that hoisting must never empty a block.
    /// </para>
    /// A leading "and ..." can never be left behind, because lead words are assigned while
    /// rendering — whatever clause a block now opens with is given its family's word.
    /// </remarks>
    /// <remarks>
    /// The act rises only as far as the subject, whose heading is named after it — <paramref
    /// name="acts"/> is false above that, where nothing names it and it would stand over
    /// requirements whose own heading says they act otherwise. Arrangement carries no such tie and
    /// rises as far as it holds.
    /// </remarks>
    private static IReadOnlyList<SpecificationClause> SharedClauses(
        Requirement[] requirements, bool acts = true)
    {
        if (requirements.Length == 0)
            return [];

        // Hoisting must never empty a block, so the shortest requirement always keeps one clause.
        var limit = requirements.Min(requirement => requirement.Clauses.Count) - 1;
        List<SpecificationClause> shared = [];
        foreach (var clause in requirements[0].Clauses)
        {
            if (shared.Count == limit)
                break;
            if (!acts && clause.Family == StepFamily.When)
                continue;
            // Repetition is part of what a clause states, so a clause rises only as many times as
            // the requirement that states it fewest times.
            var taken = shared.Count(hoisted => hoisted.Matches(clause));
            if (clause.Phase != StepPhase.Assert
                && requirements.All(requirement => requirement.Clauses.Count(clause.Matches) > taken))
                shared.Add(clause);
        }
        return shared;
    }

    /// Rendered up front because identity is the rendered text: a theory reports once per case, and
    /// cases differing only in generated values describe one and the same requirement.
    private static IEnumerable<Requirement> Distinct(IEnumerable<SpecificationEntry> entries)
        => entries
            .Select(entry => new Requirement(
                entry, SpecificationClause.Split(entry.Steps), Render(entry)))
            .DistinctBy(requirement => (
                requirement.Entry.Namespace,
                requirement.Entry.Subject,
                requirement.Entry.Branch,
                requirement.Entry.Requirement,
                requirement.Specification));

    /// The specification of a whole entry, as its identity and as the last word on ordering. Neither
    /// is written to the page, so it is measured at the page width and nothing is taken off it.
    private static string Render(SpecificationEntry entry)
        => Render(Compose(SpecificationClause.Split(entry.Steps), entry.Because), DocumentWidth);

    private static ComposedText Compose(
        IReadOnlyList<SpecificationClause> clauses, string? because, string? returns = null)
        => SpecificationRenderer.Compose(Steps(clauses, returns), because);

    private static string Render(ComposedText text, int maxLineLength)
        => text.Render(maxLineLength, ContinuationIndentation, Tolerance).NormalizeLineEndings();

    /// <summary>
    /// The steps of every clause, with the return type appended to the act as a trailing phrase —
    /// the same shape <c>because</c> takes after an assertion, and for the same reason: it qualifies
    /// the statement it follows rather than making one of its own.
    /// </summary>
    private static IEnumerable<SpecificationStep> Steps(
        IReadOnlyList<SpecificationClause> clauses, string? returns)
        => clauses.SelectMany(clause => returns is not null && clause.Family == StepFamily.When
            // No family: it qualifies the act rather than continuing it, so it takes no lead word.
            ? [.. clause.Steps, new SpecificationStep(StepLayout.Word)
                {
                    Body = $"returns {returns}",
                    Binder = ", ",
                }]
            : clause.Steps);

    /// <summary>
    /// Specification text placed under a heading. One line goes inline, because a fence is an element
    /// of its own and pays a margin above and below for text that needs neither; several lines keep
    /// the fence, which is then what tells a reader there are several. Only the code is monospaced
    /// either way — the prose around it is the document's, not the specification's.
    /// </summary>
    /// <remarks>
    /// No blank line before it: a heading and an HTML comment are both leaf blocks that end at their
    /// own line, so what follows opens a block of its own either way and the blank line would render
    /// as nothing at all.
    /// </remarks>
    private static string Block(string specification)
        => specification.Contains('\n')
            ? $"```\n{specification}\n```\n"
            : $"`{specification}`\n";

    /// <summary>
    /// How wide the document writes specification text. Wider than a test writes its own, which is
    /// read in source beside the code that produced it and shares the page with it; the document is
    /// read on its own and looks thin at that width.
    /// </summary>
    private const int DocumentWidth = 90;

    /// <summary>
    /// How far past the width a line may run rather than break — so the width is really an
    /// interval, 90 to 100. A statement a column or two over is a line a reader takes in at a
    /// glance; breaking it costs a second line, a fence around what was one line of prose, and a
    /// seam through the middle of one expression. Past the tolerance the break falls at 90, which
    /// is the whole of what the tolerance does: it decides whether to break, never where.
    /// </summary>
    private const int Tolerance = 10;

    /// How far anything written under a list item's label sits from the margin, and so how much of
    /// the page it loses. What indents the text and what measures it read the same number.
    private const int ItemIndentation = 2;

    /// <summary>
    /// How deep a wrapped line continues, in indentation steps: two — one deeper than a phrase,
    /// so a continuation cannot be read as structure. The test-spec keeps three; it is read
    /// beside code and failure output, where the extra distance earns its keep.
    /// </summary>
    private const int ContinuationIndentation = 2;

    /// What a fenced block inside an item has left of the page.
    private const int FenceWidth = DocumentWidth - ItemIndentation;

    /// What a claim has, which is two columns less again: it wears backticks and a fence does not.
    private const int ClaimWidth = FenceWidth - 2;

    /// A block inside a list item is indented to the item's own text, or it would end the list.
    private static string Indent(string block)
        => string.Join("\n",
            block.Split('\n').Select(line => $"{new string(' ', ItemIndentation)}{line}"));

    /// <summary>
    /// The lead word a heading states, which is then the one word the specification beneath it does
    /// not repeat: a heading reading "When add room" is not followed by "When ...".
    /// </summary>
    /// <remarks>
    /// Only a block's opening word is ever dropped, and only when something above it says that same
    /// word — a "Having" under a "Given" states something the heading did not, and further down the
    /// lead words are the structure of the statements they open.
    /// </remarks>
    private static string? StatedWord(string heading)
        => StepFamilies.Keywords.FirstOrDefault(
            word => heading.StartsWith($"{word} ", StringComparison.Ordinal));

    private static string Without(string? stated, string specification)
        => stated is not null && specification.StartsWith($"{stated} ", StringComparison.Ordinal)
            ? specification[(stated.Length + 1)..]
            : specification;

    /// One requirement with its specification broken into clauses, as hoisting consumes them.
    /// The rendered text rides along as its identity, and as the last word on ordering when two
    /// requirements share a name — a theory whose cases describe themselves differently.
    private sealed record Requirement(
        SpecificationEntry Entry, IReadOnlyList<SpecificationClause> Clauses, string Specification)
    {
        /// <summary>
        /// The requirement with what a heading above already states removed. Matched rather than
        /// counted, since a hoisted clause need not have been at the front — one occurrence of each,
        /// so a clause repeated within a requirement still says itself the second time.
        /// </summary>
        internal Requirement Without(IReadOnlyList<SpecificationClause> hoisted)
        {
            if (hoisted.Count == 0)
                return this;

            List<SpecificationClause> remaining = [.. Clauses];
            foreach (var clause in hoisted)
                remaining.Remove(remaining.FirstOrDefault(clause.Matches)!);
            return this with { Clauses = remaining };
        }
    }

    /// An area and its groups, each already stripped of what is stated above it. The one keyed
    /// empty holds the specs that sit at the shared root, and writes no heading of its own.
    private sealed record AreaNode(
        string Key, IReadOnlyList<SpecificationClause> Shared, Declared Declaration, GroupNode[] Groups)
    {
        internal int ComplexityNumber
            => Arrangement(Shared) + Groups.Sum(group => group.ComplexityNumber);
    }

    /// What an area's namespaces differ in below it, and the subjects written there. An area with
    /// one of these writes no heading for it and hands its subjects straight on.
    private sealed record GroupNode(
        string Key, IReadOnlyList<SpecificationClause> Shared, Declared Declaration, SubjectNode[] Subjects)
    {
        internal int ComplexityNumber
            => Arrangement(Shared) + Subjects.Sum(subject => subject.ComplexityNumber);
    }

    /// A subject and its branches, each already stripped of what is stated above it.
    private sealed record SubjectNode(
        string Key, IReadOnlyList<SpecificationClause> Shared, Declared Declaration, BranchNode[] Branches)
    {
        internal int ComplexityNumber
            => Arrangement(Shared) + Branches.Sum(branch => branch.ComplexityNumber);
    }

    /// A branch and its requirements. A subject with no branches has one of these with an empty key.
    private sealed record BranchNode(
        string Key, IReadOnlyList<SpecificationClause> Shared, Requirement[] Requirements)
    {
        internal int ComplexityNumber
            => Arrangement(Shared) + Requirements.Sum(requirement => Arrangement(requirement.Clauses));
    }
}
