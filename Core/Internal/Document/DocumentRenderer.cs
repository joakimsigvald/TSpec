using System.Text;
using TSpec.Internal.Specification;

namespace TSpec.Internal.Document;

/// <summary>
/// Renders the specification document. Entries are fully sorted and the specification text is
/// normalized to LF — <c>Specification.ToString()</c> is documented to return platform-native line
/// endings, so a Windows run would otherwise commit a file that differs from a Linux one on every
/// line. Together this makes the document byte-identical on every machine, which is what lets its
/// diff be reviewed.
/// </summary>
internal static class DocumentRenderer
{
    internal static string Render(
        SpecificationSubject subject, string specAssemblyName, string buildId,
        IEnumerable<SpecificationEntry> entries)
    {
        var text = new StringBuilder()
            .Append($"# {subject.Name}\n\n")
            .Append($"Version {subject.Version}, hash {buildId}\n\n")
            .Append($"<!-- Generated by TSpec from {specAssemblyName}. Do not edit by hand. -->\n");
        foreach (var group in Ordered(entries).GroupBy(entry => entry.Subject))
        {
            text.Append($"\n## {group.Key}\n");
            foreach (var entry in group)
                text.Append($"\n### {Heading(entry)}\n\n```\n{entry.Text.NormalizeLineEndings()}\n```\n");
        }
        return text.ToString();
    }

    private static IEnumerable<SpecificationEntry> Ordered(IEnumerable<SpecificationEntry> entries)
        => entries
            .Distinct()
            .OrderBy(entry => entry.Subject, StringComparer.Ordinal)
            .ThenBy(entry => entry.Branch, StringComparer.Ordinal)
            .ThenBy(entry => entry.Requirement, StringComparer.Ordinal);

    private static string Heading(SpecificationEntry entry)
        => entry.Branch.Length == 0 ? entry.Requirement : $"{entry.Branch}.{entry.Requirement}";
}
