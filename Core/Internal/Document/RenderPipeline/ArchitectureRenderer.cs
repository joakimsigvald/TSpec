using TSpec.Architecture;
using TSpec.Internal.Specification;

namespace TSpec.Internal.Document.RenderPipeline;

/// The page an architecture spec writes: the solution its projects are named under, the graph of
/// their references, and its tests as any specification renders them.
internal static class ArchitectureRenderer
{
    internal const string FileName = "_specification.md";

    internal static string Render(
        SourceProjects projects, string specAssemblyName, IEnumerable<SpecificationEntry> entries,
        IReadOnlyDictionary<string, string> indexes)
        => projects.Graph.SharedNamespace is { } shared
            ? Render(projects.Under(shared), shared.Segment(^1), specAssemblyName, entries, indexes)
            : Render(projects, specAssemblyName, specAssemblyName, entries, indexes);

    private static string Render(
        SourceProjects projects, string title, string specAssemblyName, IEnumerable<SpecificationEntry> entries,
        IReadOnlyDictionary<string, string> indexes)
    {
        DocumentSegment[] segments = [
            new TitleSegment(title.AsTitle()),
            new CommentSegment($"Generated by TSpec from {specAssemblyName}. Do not edit by hand."),
            ProjectGraphSegment.Of(projects, indexes),
            .. DocumentRenderer.Bodies(title, specAssemblyName, entries)];
        return segments.Render();
    }
}
