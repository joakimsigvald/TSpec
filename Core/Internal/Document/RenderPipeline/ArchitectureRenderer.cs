using TSpec.Architecture;
using TSpec.Internal.Specification;

namespace TSpec.Internal.Document.RenderPipeline;

/// The page an architecture spec writes: the solution its projects are named under, and the graph
/// of their references.
internal static class ArchitectureRenderer
{
    internal const string FileName = "_specification.md";

    internal static string Render(SourceProjects graph, string specAssemblyName)
        => graph.SharedNamespace is { } shared
            ? Render(graph.Under(shared), shared.Segment(^1), specAssemblyName)
            : Render(graph, specAssemblyName, specAssemblyName);

    private static string Render(SourceProjects graph, string title, string specAssemblyName)
        => new DocumentSegment[]
        {
            new TitleSegment(title.AsTitle()),
            new CommentSegment($"Generated by TSpec from {specAssemblyName}. Do not edit by hand."),
            new ProjectGraphSegment(graph),
        }.Render();
}
