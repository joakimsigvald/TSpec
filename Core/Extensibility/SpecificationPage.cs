using System.Reflection;
using TSpec.Internal.Document;
using TSpec.Internal.Document.RenderPipeline;
using TSpec.Internal.Specification;

namespace TSpec.Extensibility;

/// <summary>
/// A page an extension package writes to the spec project at the end of a run in which every test of a
/// <see cref="Spec"/> class passed: a title, what the package states, and the tests below it, each folder
/// of the spec project under a heading and each test class linked to its file. Enable it with one line in
/// the spec project: <code>[assembly: AssemblyFixture(typeof(ThePage))]</code>
/// </summary>
public abstract class SpecificationPage : IDisposable
{
    private readonly string _fileName;
    private readonly Assembly _specAssembly;
    private readonly string? _directory;

    /// <summary>
    /// Locates the spec project the page is written to, or reports why it could not
    /// </summary>
    /// <param name="fileName">The page's file name in the spec project's folder: "_specification.md"</param>
    protected SpecificationPage(string fileName)
    {
        _fileName = fileName;
        _specAssembly = CompleteRun.SpecAssemblyDeclaring(GetType());
        CompleteRun.Begin(
            fileName,
            located: ProjectDirectory.TryLocate(SpecClasses.SourcesOf(_specAssembly), AppContext.BaseDirectory, out _directory));
    }

    /// <summary>
    /// The name of the spec project's assembly
    /// </summary>
    protected string SpecAssemblyName => _specAssembly.GetName().Name!;

    /// <summary>
    /// What the page is about, as a name its title reads in words: "MyHotel" titles it "My Hotel"
    /// </summary>
    protected abstract string Subject { get; }

    /// <summary>
    /// What the page states between its title and the tests, in Markdown
    /// </summary>
    /// <param name="directory">The spec project's folder, which the page sits in and links from</param>
    /// <returns>The Markdown, or empty for none</returns>
    protected abstract string Header(string directory);

    /// <summary>
    /// Writes the page where the run was complete and green, or names the tests that kept it from being so
    /// </summary>
    public void Dispose()
    {
        GC.SuppressFinalize(this);
        var directory = _directory;
        if (directory is null)
            return;

        CompleteRun.End(_fileName, _specAssembly, entries => PendingSpecification.Write(
            Path.Combine(directory, _fileName), Render(Subject, SpecAssemblyName, Header(directory), entries, directory)));
    }

    internal static string Render(
        string subject, string specAssemblyName, string header, IEnumerable<SpecificationEntry> entries, string? sourceRoot)
    {
        DocumentSegment[] segments = [
            new TitleSegment(subject.AsTitle()),
            new CommentSegment($"Generated by TSpec from {specAssemblyName}. Do not edit by hand."),
            .. HeaderOf(header),
            .. DocumentRenderer.Sections(subject, specAssemblyName, entries, sourceRoot)];
        return segments.Render();
    }

    private static DocumentSegment[] HeaderOf(string header) => header.Length == 0 ? [] : [new MarkdownSegment(header)];
}
