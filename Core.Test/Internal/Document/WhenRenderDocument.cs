using TSpec.Assert;
using TSpec.Internal.Document;
using TSpec.Internal.Specification;

namespace TSpec.Test.Internal.Document;

public class WhenRenderDocument : Spec
{
    private const string Header =
        "# MyHotel\n"
        + "\n"
        + "Version 0.1.0, hash 4f2a9c1e\n"
        + "\n"
        + "<!-- Generated by TSpec from MyHotel.Spec. Do not edit by hand. -->\n";

    private static readonly SpecificationSubject _myHotel = new("MyHotel", "0.1.0");

    private static readonly SpecificationEntry _respondOk = new(
        "WhenGetVersion", "GivenNothing", "ThenRespondOk",
        Sentences(
            "using owned CreateClient",
            "when api.GetAsync(\"/version\")",
            "then Result.StatusCode is HttpStatusCode.OK"));

    /// The document takes described steps, so a test that is about layout rather than about
    /// description supplies the simplest step there is: one sentence per line.
    private static SpecificationStep[] Sentences(params string[] sentences)
        => [.. sentences.Select(sentence => new SpecificationStep(StepLayout.Sentence) { Body = sentence })];

    private static string Render(params SpecificationEntry[] entries)
        => DocumentRenderer.Render(_myHotel, "MyHotel.Spec", "4f2a9c1e", entries);

    [Fact] public void GivenNoEntries_ThenRenderTheHeaderAlone() => Render().Is(Header);

    [Fact]
    public void ThenNameTheBuildTheDocumentCameFrom()
        => Render().Does().Contain("Version 0.1.0, hash 4f2a9c1e");

    [Fact]
    public void ThenRenderTheRequirementUnderItsSubject()
        => Render(_respondOk).Is(
            Header
            + "\n"
            + "## WhenGetVersion\n"
            + "\n"
            + "### GivenNothing.ThenRespondOk\n"
            + "\n"
            + "```\n"
            + "Using owned CreateClient\n"
            + "When api.GetAsync(\"/version\")\n"
            + "Then Result.StatusCode is HttpStatusCode.OK\n"
            + "```\n");

    [Fact]
    public void GivenNoBranch_ThenHeadTheRequirementByNameAlone()
        => Render(_respondOk with { Branch = "" }).Does().Contain("### ThenRespondOk\n");

    /// <summary>Two requirements of one subject share a single subject heading.</summary>
    [Fact]
    public void ThenGroupRequirementsBySubject()
    {
        var document = Render(_respondOk, _respondOk with { Requirement = "ThenReturnVersion" });
        document.Split("## WhenGetVersion").Length.Is(2);
        document.Does().Contain("### GivenNothing.ThenRespondOk").and.Contain("### GivenNothing.ThenReturnVersion");
    }

    [Fact]
    public void GivenEntriesOutOfOrder_ThenSortThem()
        => Render(_respondOk with { Requirement = "ThenB" }, _respondOk with { Requirement = "ThenA" })
            .Does().Contain("### GivenNothing.ThenA").and.Contain("### GivenNothing.ThenB");

    /// <summary>A theory reports once per case; identical text must not repeat in the document.</summary>
    [Fact]
    public void GivenDuplicateEntries_ThenRenderOne()
        => Render(_respondOk, _respondOk).Is(Render(_respondOk));

    /// <summary>The specification is built with Environment.NewLine, so it comes back CRLF on Windows.</summary>
    [Fact]
    public void ThenNormaliseLineEndingsToLf()
        => Render(_respondOk with { Steps = Sentences("when a", "then b") })
            .Does().Contain("```\nWhen a\nThen b\n```").and.not.Contain("\r");

    // ----------- Setup shared by a whole subject is stated once, under its heading

    private static SpecificationStep Using(string body)
        => new(StepLayout.SentenceOrPhrase) { Family = StepFamily.Using, Body = body };

    /// A requirement opening with the shared setup, then saying something of its own.
    private static SpecificationEntry Requirement(string name, params SpecificationStep[] ownSteps)
        => new("WhenGetRoom", "GivenNoSuchRoom", name,
            [Using("api"), Using("api.CreateClient"), .. ownSteps]);

    private static SpecificationEntry[] ThreeRequirements()
        => [Requirement("ThenA", Sentences("then a")[0]),
            Requirement("ThenB", Sentences("then b")[0]),
            Requirement("ThenC", Sentences("then c")[0])];

    [Fact]
    public void GivenEveryRequirementOpensWithTheSameSetup_ThenStateItUnderTheSubject()
        => Render(ThreeRequirements()).Does()
            .Contain("## WhenGetRoom\n\n```\nUsing api\n  and api.CreateClient\n```\n")
            .and.Contain("### GivenNoSuchRoom.ThenA\n\n```\nThen a\n```\n");

    /// <summary>The hoisted run is complete, so nothing is left behind to head the block.</summary>
    [Fact]
    public void GivenSetupIsShared_ThenLeaveNoneOfItInTheBlocks()
        => Render(ThreeRequirements()).Does().not.Contain("```\nAnd api.CreateClient");

    /// <summary>Two requirements are not repetition worth factoring out.</summary>
    [Fact]
    public void GivenFewerThanThreeRequirements_ThenLeaveTheSetupInPlace()
        => Render(ThreeRequirements()[..2]).Does()
            .Contain("```\nUsing api\n  and api.CreateClient\nThen a\n```")
            .and.not.Contain("## WhenGetRoom\n\n```");

    [Fact]
    public void GivenOneRequirementOpensDifferently_ThenLeaveTheSetupInPlace()
    {
        var requirements = ThreeRequirements();
        requirements[2] = requirements[2] with { Steps = [Using("api"), .. Sentences("then c")] };
        Render(requirements).Does().not.Contain("## WhenGetRoom\n\n```");
    }

    /// <summary>Hoisting must never empty a block, so a requirement that is only setup blocks it.</summary>
    [Fact]
    public void GivenARequirementIsNothingButTheSharedSetup_ThenLeaveTheSetupInPlace()
    {
        var requirements = ThreeRequirements();
        requirements[2] = requirements[2] with { Steps = [Using("api"), Using("api.CreateClient")] };
        Render(requirements).Does().not.Contain("## WhenGetRoom\n\n```");
    }
}
