using TSpec.Assert;
using TSpec.Internal.Document;
using TSpec.Internal.Specification;

namespace TSpec.Test.Internal.Document;

public class WhenRenderDocument : Spec
{
    private const string Header =
        "# My Hotel\n"
        + "\n"
        + "<!-- Version 0.1.0+4f2a9c1e, generated by TSpec from MyHotel.Spec. Do not edit by hand. -->\n";

    private static readonly SpecificationSubject _myHotel = new("MyHotel", "0.1.0");

    private static readonly SpecificationEntry _respondOk = new(
        "WhenGetVersion", "GivenNothing", "ThenRespondOk",
        Sentences(
            "using owned CreateClient",
            "when api.GetAsync(\"/version\")",
            "then Result.StatusCode is HttpStatusCode.OK"));

    /// The document takes described steps, so a test that is about layout rather than about
    /// description supplies the simplest step there is: one sentence per line.
    private static SpecificationStep[] Sentences(params string[] sentences)
        => [.. sentences.Select(sentence => new SpecificationStep(StepLayout.Sentence) { Body = sentence })];

    private static string Render(params SpecificationEntry[] entries)
        => DocumentRenderer.Render(_myHotel, "MyHotel.Spec", "4f2a9c1e", entries);

    [Fact] public void GivenNoEntries_ThenRenderTheHeaderAlone() => Render().Is(Header);

    /// <summary>Provenance, so that a document nobody regenerated is not mistaken for one that was.</summary>
    [Fact]
    public void ThenNameTheBuildTheDocumentCameFrom()
        => Render().Does().Contain("Version 0.1.0+4f2a9c1e");

    /// <summary>
    /// A project named for a layer is dotted — "MyHotel.Core" — and there the dot separates parts of
    /// one name, not one sentence from the next. A branch path is the opposite case, which is why
    /// <c>AsHeading</c> splits it into sentences and a title does not.
    /// </summary>
    [Fact]
    public void GivenADottedSubjectName_ThenTitleItAsOneName()
        => DocumentRenderer.Render(new("MyHotel.Core", "0.1.0"), "MyHotel.Core.Spec", "4f2a9c1e", [])
            .Does().StartWith("# My Hotel Core\n");

    [Fact]
    public void ThenRenderTheRequirementUnderItsSubject()
        => Render(_respondOk).Is(
            Header
            + "\n"
            + "## When get version\n"
            + "\n"
            + "### Given nothing\n"
            + "\n"
            + "- **respond ok**\n"
            + "  ```\n"
            + "  Using owned CreateClient\n"
            + "  When api.GetAsync(\"/version\")\n"
            + "  Then Result.StatusCode is HttpStatusCode.OK\n"
            + "  ```\n");

    /// <summary>
    /// A requirement is an item of a list wherever it sits, so a subject with no branch loses a
    /// level of nesting rather than a level of heading.
    /// </summary>
    [Fact]
    public void GivenNoBranch_ThenListTheRequirementUnderTheSubject()
        => Render(_respondOk with { Branch = "" }).Does()
            .Contain("## When get version\n\n- **respond ok**\n").and.not.Contain("###");

    /// <summary>Two requirements of one subject share a single subject heading.</summary>
    [Fact]
    public void ThenGroupRequirementsBySubject()
    {
        var document = Render(_respondOk, _respondOk with { Requirement = "ThenReturnVersion" });
        document.Split("## When get version").Length.Is(2);
        document.Does().Contain("- **respond ok**").and.Contain("- **return version**");
        document.Split("### Given nothing\n").Length.Is(2);
    }

    [Fact]
    public void GivenEntriesOutOfOrder_ThenSortThem()
        => Render(_respondOk with { Requirement = "ThenB" }, _respondOk with { Requirement = "ThenA" })
            .Does().Contain("- **a**\n").and.Contain("- **b**\n");

    /// <summary>A theory reports once per case; identical text must not repeat in the document.</summary>
    [Fact]
    public void GivenDuplicateEntries_ThenRenderOne()
        => Render(_respondOk, _respondOk).Is(Render(_respondOk));

    /// <summary>The specification is built with Environment.NewLine, so it comes back CRLF on Windows.</summary>
    [Fact]
    public void ThenNormaliseLineEndingsToLf()
        => Render(_respondOk with { Steps = Sentences("when a", "then b") })
            .Does().Contain("When a\n  Then b").and.not.Contain("\r");

    // ----------- A heading states the context, and the requirements under it are a list

    private static SpecificationStep Using(string body)
        => new(StepLayout.SentenceOrPhrase) { Family = StepFamily.Using, Body = body };

    private static SpecificationStep Act(string body)
        => new(StepLayout.SentenceOrPhrase) { Family = StepFamily.When, Body = body };

    /// An assertion heading its own line, which is the one clause with no family.
    private static SpecificationStep Claim(string body)
        => new(StepLayout.Sentence) { Body = body };

    private static SpecificationStep Condition(string body)
        => new(StepLayout.SentenceOrPhrase) { Family = StepFamily.Having, Body = body };

    private static SpecificationEntry Requirement(
        string subject, string name, params SpecificationStep[] steps)
        => new(subject, "", name, steps);

    /// <summary>
    /// One statement under a heading is written inline, where a fence would be an element of its own
    /// paying a margin above and below for a single line — and it drops the word the heading has
    /// already said.
    /// </summary>
    [Fact]
    public void GivenAHeadingStatesOneClause_ThenWriteItInlineWithoutTheWordItSaid()
        => Render(
            Requirement("WhenGetRoom", "ThenA", Act("get"), Claim("then a")),
            Requirement("WhenAddRoom", "ThenB", Act("post"), Claim("then b")))
            .Does().Contain("## When get room\n`get`\n");

    /// <summary>
    /// A requirement is an item of a list: its name reads the claim and the claim stands beside it,
    /// neither of them saying the "then" that the item's place in the list says already.
    /// </summary>
    [Fact]
    public void ThenWriteARequirementAsAListItem()
        => Render(Requirement("WhenGetRoom", "ThenRespondOk", Act("get"), Claim("then Result is OK")))
            .Does().Contain("- **respond ok** — `Result is OK`\n");

    /// <summary>
    /// A requirement that states more than its claim keeps the fence, indented into its own item so
    /// that the list survives it — and keeps its lead words, which are what orders the statements.
    /// </summary>
    [Fact]
    public void GivenARequirementStatesSeveralThings_ThenFenceThemInsideItsItem()
        => Render(
            Requirement("WhenGetRoom", "ThenA", Act("get"), Condition("post"), Claim("then a")),
            Requirement("WhenGetRoom", "ThenB", Act("get"), Claim("then b")))
            .Does().Contain("- **a**\n  ```\n  Having post\n  Then a\n  ```\n");

    // ----------- What every requirement of a group opens with is stated once for the group

    /// <summary>
    /// A condition shared by a branch's requirements belongs at the branch heading, which is the
    /// one place naming it agrees with what it says.
    /// </summary>
    [Fact]
    public void GivenABranchOpensAlike_ThenStateThatOnceForTheBranch()
    {
        SpecificationEntry OfBranch(string branch, string name, params SpecificationStep[] own)
            => new("WhenGetRoom", branch, name, [Using("api"), Act("get"), .. own]);
        Render(
            OfBranch("GivenTheRoomExists", "ThenA", Condition("post"), Claim("then a")),
            OfBranch("GivenTheRoomExists", "ThenB", Condition("post"), Claim("then b")),
            OfBranch("GivenNoSuchRoom", "ThenC", Claim("then c")),
            OfBranch("GivenNoSuchRoom", "ThenD", Claim("then d")))
            .Does()
            .Contain("### Given the room exists\n`Having post`\n")
            .and.Contain("- **a** — `a`\n")
            .and.Contain("### Given no such room\n\n- **c** — `c`\n");
    }

    /// Two subjects that share their arrangement but each have their own action.
    private static SpecificationEntry[] TwoSubjects()
        => [.. new[] { "a", "b", "c" }.Select(name =>
                Requirement("WhenGetRoom", $"Then{name}",
                    Using("api"), Act("get"), Claim($"then {name}"))),
            .. new[] { "d", "e", "f" }.Select(name =>
                Requirement("WhenAddRoom", $"Then{name}",
                    Using("api"), Act("post"), Claim($"then {name}")))];

    /// <summary>Shared by every requirement in the document, so it rises above the subjects.</summary>
    [Fact]
    public void GivenEveryRequirementOpensAlike_ThenStateThatOnceForTheDocument()
        => Render(TwoSubjects()).Does()
            .Contain("Do not edit by hand. -->\n`Using api`\n\n## When add room");

    /// <summary>Shared within one subject only, so it settles at that subject's heading.</summary>
    [Fact]
    public void GivenOneSubjectOpensAlike_ThenStateThatOnceForTheSubject()
        => Render(TwoSubjects()).Does()
            .Contain("## When add room\n`post`\n")
            .and.Contain("## When get room\n`get`\n")
            .and.Contain("- **Thena** — `a`\n");

    /// <summary>
    /// An assertion is the claim a requirement exists to make. Two requirements agreeing on one
    /// is worth seeing, so it stays in both blocks however often it repeats.
    /// </summary>
    [Fact]
    public void GivenEveryRequirementClaimsTheSame_ThenStillStateItInEachBlock()
        => Render([.. new[] { "a", "b", "c" }.Select(name =>
                Requirement("WhenGetRoom", $"Then{name}", Claim("then same"), Claim($"then {name}")))])
            .Split("same").Length.Is(4);

    /// <summary>
    /// A lone requirement shares nothing with anyone, but its context still belongs under the
    /// heading — there is no minimum number of requirements before a heading may hold what names it.
    /// </summary>
    [Fact]
    public void GivenASingleRequirement_ThenStillStateItsOpeningAbove()
        => Render(TwoSubjects()[..1]).Does()
            .Contain("-->\n```\nUsing api\nWhen get\n```\n")
            .and.Contain("- **Thena** — `a`\n");

    /// <summary>Two are already repetition — the second saying it again is what makes it so.</summary>
    [Fact]
    public void GivenTwoRequirementsOpenAlike_ThenStateTheOpeningOnce()
        => Render(TwoSubjects()[..2]).Does()
            .Contain("-->\n```\nUsing api\nWhen get\n```\n")
            .and.Contain("- **Thena** — `a`\n");

    /// <summary>
    /// One requirement saying something else keeps that clause in every block — but only that one.
    /// What the others still agree on is decided on its own and rises anyway.
    /// </summary>
    [Fact]
    public void GivenOneRequirementSaysSomethingElse_ThenLeaveThatClauseInPlace()
    {
        var requirements = TwoSubjects()[..3];
        requirements[2] = requirements[2] with { Steps = [Using("other"), Act("get"), Claim("then c")] };
        Render(requirements).Does()
            .Contain("-->\n`When get`\n")
            .and.Contain("- **Thena**\n  ```\n  Using api\n  Then a\n  ```\n")
            .and.Contain("- **Thenc**\n  ```\n  Using other\n  Then c\n  ```\n");
    }

    /// <summary>Hoisting must never empty a block, so a requirement that is only the opening blocks it.</summary>
    [Fact]
    public void GivenARequirementIsNothingButTheSharedOpening_ThenLeaveTheOpeningInPlace()
    {
        var requirements = TwoSubjects()[..3];
        requirements[2] = requirements[2] with { Steps = [Using("api")] };
        Render(requirements).Does().Contain("-->\n\n## ");
    }

    /// <summary>
    /// A clause is stated at a heading because every requirement below says it, not because it comes
    /// first. Arrangement runs before the act, so a branch that arranges anything of its own would
    /// otherwise sit in front of the shared <c>When</c> and keep it out of the heading that names it.
    /// </summary>
    [Fact]
    public void GivenTheSharedClauseSitsBehindADifferingOne_ThenStillStateItAtTheHeading()
        => Render(
            Requirement("WhenDeleteRoom", "ThenA", Condition("load none"), Act("delete"), Claim("then a")),
            Requirement("WhenDeleteRoom", "ThenB", Condition("load one"), Act("delete"), Claim("then b")),
            Requirement("WhenAddRoom", "ThenC", Condition("load one"), Act("add"), Claim("then c")))
            .Does()
            .Contain("## When delete room\n`delete`\n")
            .and.Contain("- **a**\n  ```\n  Having load none\n  Then a\n  ```\n");

    /// <summary>The mirror: what differs may come second and what is shared first.</summary>
    [Fact]
    public void GivenTheSharedClauseComesFirst_ThenStillStateItAtTheHeading()
        => Render(
            Requirement("WhenGetRoom", "ThenA", Act("get"), Condition("post once"), Claim("then a")),
            Requirement("WhenGetRoom", "ThenB", Act("get"), Condition("post twice"), Claim("then b")),
            Requirement("WhenAddRoom", "ThenC", Act("add"), Condition("post once"), Claim("then c")))
            .Does().Contain("## When get room\n`get`\n");

    /// <summary>
    /// How often a clause is stated is part of what it states — two identical setups are two
    /// invocations — so a clause rises only as many times as every requirement says it. Hoisting it
    /// twice above a requirement that says it once would put a claim on the page nothing made.
    /// </summary>
    [Fact]
    public void GivenOneRequirementSaysAClauseFewerTimes_ThenRaiseItOnlyThatOften()
        => Render(
            Requirement("WhenGetRoom", "ThenA",
                Condition("post"), Condition("post"), Act("get"), Claim("then a")),
            Requirement("WhenGetRoom", "ThenB", Condition("post"), Act("get"), Claim("then b")))
            .Does()
            .Contain("-->\n```\nHaving post\nWhen get\n```\n")
            .and.Contain("- **a**\n  ```\n  Having post\n  Then a\n  ```\n")
            .and.Contain("- **b** — `b`\n");

    /// <summary>Said twice by every requirement, so it rises twice and none of it is left below.</summary>
    [Fact]
    public void GivenEveryRequirementSaysAClauseTwice_ThenRaiseItTwice()
        => Render(
            Requirement("WhenGetRoom", "ThenA", Condition("post"), Condition("post"), Claim("then a")),
            Requirement("WhenGetRoom", "ThenB", Condition("post"), Condition("post"), Claim("then b")))
            .Does()
            .Contain("-->\n```\nHaving post\n  after post\n```\n")
            .and.Contain("- **a** — `a`\n");

    /// <summary>
    /// One requirement not saying it is enough to keep it out — no partial credit. The clause every
    /// requirement does share still rises, so the two are decided one at a time.
    /// </summary>
    [Fact]
    public void GivenOneRequirementLacksTheClause_ThenLeaveThatOneInEachBlock()
        => Render(
            Requirement("WhenGetRoom", "ThenA", Condition("load"), Act("get"), Claim("then a")),
            Requirement("WhenGetRoom", "ThenB", Condition("load"), Act("get"), Claim("then b")),
            Requirement("WhenGetRoom", "ThenC", Condition("load"), Claim("then c")))
            .Does()
            .Contain("-->\n`Having load`\n")
            .and.not.Contain("## When get room\n`get`\n");

    // ----------- What the spec declares about the code, stated where it holds

    /// <summary>
    /// The types ground the requirements in the code they describe, so they are stated rather than
    /// phrased — a sentence would have to read well for every spec, and Spec&lt;int&gt; over a static
    /// calculation defeats any of them.
    /// </summary>
    [Fact]
    public void GivenEverySpecDeclaresTheSame_ThenStateItForTheDocument()
        => Render(_respondOk with { SubjectUnderTest = "HttpClient", ReturnType = "HttpResponseMessage" })
            .Does().Contain("-->\n```\nSubject under test: HttpClient\nReturn type:        HttpResponseMessage\n");

    /// <summary>The two values are read as a pair, so they are set in a column under one another.</summary>
    [Fact]
    public void ThenLineUpTheDeclaredTypes()
        => Render(_respondOk with { SubjectUnderTest = "int", ReturnType = "string" })
            .Does().Contain("Subject under test: int\nReturn type:        string\n");

    /// <summary>
    /// A return type is what the act yields, so where a heading states both it joins the act instead
    /// of standing as a label of its own. The subject has no clause to belong to and stays a label.
    /// </summary>
    [Fact]
    public void GivenAHeadingStatesTheReturnTypeAndTheAct_ThenSayItOnTheAct()
        => Render(
            Requirement("WhenGetRoom", "ThenA", Act("get"), Claim("then a"))
                with { SubjectUnderTest = "HttpClient", ReturnType = "HttpResponseMessage" },
            Requirement("WhenAdd", "ThenB", Act("add"), Claim("then b"))
                with { SubjectUnderTest = "int", ReturnType = "int" })
            .Does().Contain("## When add\n```\nSubject under test: int\nWhen add, returns int\n```");

    /// <summary>With no act at the heading it has nothing to join, so it stays a label.</summary>
    [Fact]
    public void GivenAHeadingStatesTheReturnTypeAlone_ThenKeepItALabel()
        => Render(_respondOk with { SubjectUnderTest = "HttpClient", ReturnType = "HttpResponseMessage" })
            .Does().Contain("Return type:        HttpResponseMessage\n");

    [Fact]
    public void GivenSpecsDeclareDifferently_ThenStateItForEachSubject()
        => Render(
            Requirement("WhenGetRoom", "ThenA", Act("get"), Claim("then a"))
                with { SubjectUnderTest = "HttpClient", ReturnType = "HttpResponseMessage" },
            Requirement("WhenAdd", "ThenB", Act("add"), Claim("then b"))
                with { SubjectUnderTest = "int", ReturnType = "int" })
            .Does()
            .Contain("## When get room\n```\nSubject under test: HttpClient\n")
            .and.Contain("## When add\n```\nSubject under test: int\n");

    /// <summary>Stated where it holds and not again below, since saying it once is the point.</summary>
    [Fact]
    public void GivenTheDocumentStatesTheTypes_ThenDoNotRepeatThemPerSubject()
        => Render([.. TwoSubjects().Select(entry => entry with
                { SubjectUnderTest = "HttpClient", ReturnType = "HttpResponseMessage" })])
            .Split("Subject under test").Length.Is(2);

    [Fact]
    public void GivenTheSpecDeclaresNothing_ThenSayNothingAboutTypes()
        => Render(_respondOk).Does().not.Contain("Subject under test");

    /// One subject throughout, each section returning something of its own.
    private static SpecificationEntry[] OneSubjectManyReturnTypes()
        => [Requirement("WhenGetRoom", "ThenA", Act("get"), Claim("then a"))
                with { SubjectUnderTest = "RoomService", ReturnType = "Room" },
            Requirement("WhenListRooms", "ThenB", Act("list"), Claim("then b"))
                with { SubjectUnderTest = "RoomService", ReturnType = "Room[]" }];

    /// <summary>
    /// The two labels are hoisted one at a time. Held together, a single disagreeing return type
    /// would drag the subject down with it and have every section restate a name that never changes.
    /// </summary>
    [Fact]
    public void GivenOneSubjectDeclaresSeveralReturnTypes_ThenStillStateTheSubjectForTheDocument()
        => Render(OneSubjectManyReturnTypes()).Does()
            .Contain("-->\n`Subject under test: RoomService`\n")
            .and.Contain("## When get room\n`get, returns Room`\n")
            .and.Contain("## When list rooms\n`list, returns Room[]`\n");

    /// <summary>Hoisted is stated once: the subject does not come back under each section.</summary>
    [Fact]
    public void GivenTheDocumentStatesTheSubject_ThenDoNotRepeatItPerSubject()
        => Render(OneSubjectManyReturnTypes()).Split("Subject under test").Length.Is(2);

    /// <summary>The same the other way round, so neither label is the one that happens to work.</summary>
    [Fact]
    public void GivenSeveralSubjectsDeclareOneReturnType_ThenStillStateItForTheDocument()
        => Render(
            Requirement("WhenGetRoom", "ThenA", Act("get"), Claim("then a"))
                with { SubjectUnderTest = "RoomService", ReturnType = "Room" },
            Requirement("WhenAdd", "ThenB", Act("add"), Claim("then b"))
                with { SubjectUnderTest = "RoomStore", ReturnType = "Room" })
            .Does()
            .Contain("-->\n`Return type: Room`\n")
            .and.Contain("## When add\n```\nSubject under test: RoomStore\nWhen add\n```");

    /// <summary>
    /// The column is what makes two labels read as a pair. One standing on its own has nothing to
    /// line up with, so padding it would leave a gap the reader has to account for.
    /// </summary>
    [Fact]
    public void GivenAHeadingStatesOneLabelAlone_ThenWriteItWithoutTheColumn()
        => Render(OneSubjectManyReturnTypes()).Does().not.Contain("Return type:  ");

    // ----------- Sections are ordered by how much arrangement they carry, simplest first

    /// <summary>
    /// The document's sections in the order they appear: each heading as it reads, and each
    /// requirement by the label that names it, which is all an ordering rule can be seen in.
    /// </summary>
    private static string[] Outline(string document)
        => [.. document.Split('\n')
            .Where(line => line.StartsWith("##", StringComparison.Ordinal) || IsItem(line))
            .Select(line => IsItem(line) ? Label(line) : line)];

    private static bool IsItem(string line) => line.StartsWith("- **", StringComparison.Ordinal);

    /// An item's label, without the claim standing beside it.
    private static string Label(string item)
        => item[..(item.IndexOf("**", 4, StringComparison.Ordinal) + 2)];

    private static string[] SubjectHeadings(string document)
        => [.. document.Split('\n').Where(line => line.StartsWith("## ", StringComparison.Ordinal))];

    /// <summary>
    /// The alphabetically first subject is the one that arranges more, and it comes last — so the
    /// order is the rule's and not the alphabet's.
    /// </summary>
    [Fact]
    public void GivenOneSubjectArrangesMore_ThenPlaceTheSimplerFirst()
        => Outline(Render(
            new("WhenAddRoom", "GivenNoSuchRoom", "ThenA", [Act("post"), Claim("then a")]),
            new("WhenAddRoom", "GivenTheRoomExists", "ThenB", [Act("post"), Condition("post"), Claim("then b")]),
            new("WhenGetVersion", "", "ThenC", [Act("get"), Claim("then c")])))
            .Is().EqualTo([
                "## When get version",
                "- **c**",
                "## When add room",
                "### Given no such room",
                "- **a**",
                "### Given the room exists",
                "- **b**"]);

    [Fact]
    public void GivenOneBranchArrangesMore_ThenPlaceTheSimplerFirst()
        => Outline(Render(
            new("WhenGetRoom", "GivenAaa", "ThenA", [Act("get"), Condition("post"), Claim("then a")]),
            new("WhenGetRoom", "GivenZzz", "ThenB", [Act("get"), Claim("then b")])))
            .Is().EqualTo([
                "## When get room",
                "### Given zzz",
                "- **b**",
                "### Given aaa",
                "- **a**"]);

    [Fact]
    public void GivenOneRequirementArrangesMore_ThenPlaceTheSimplerFirst()
        => Outline(Render(
            new("WhenGetRoom", "GivenX", "ThenA", [Act("get"), Condition("post"), Claim("then a")]),
            new("WhenGetRoom", "GivenX", "ThenB", [Act("get"), Claim("then b")])))
            .Is().EqualTo(["## When get room", "### Given x", "- **b**", "- **a**"]);

    /// <summary>
    /// Requirements that arrange alike are ordered by how much they claim, so a short status check
    /// precedes one that inspects a whole value. Length only ever breaks a tie — it never overrides
    /// arrangement, and it decides nothing above the leaf.
    /// </summary>
    [Fact]
    public void GivenTwoRequirementsArrangeAlike_ThenPlaceTheShorterClaimFirst()
        => Outline(Render(
            new("WhenGetRoom", "GivenX", "ThenA", [Act("get"), Claim("then the whole room is returned")]),
            new("WhenGetRoom", "GivenX", "ThenB", [Act("get"), Claim("then ok")])))
            .Is().EqualTo(["## When get room", "### Given x", "- **b**", "- **a**"]);

    /// <summary>
    /// Assertions are not counted, and this is why: a suite grows by claiming more, and a document
    /// that reshuffled every time it did would spend the diff it is reviewed for.
    /// </summary>
    [Fact]
    public void GivenARequirementIsAdded_ThenLeaveTheOrderOfSubjectsAlone()
    {
        SpecificationEntry[] before = [
            new("WhenAaa", "", "ThenA", [Act("aaa"), Condition("post"), Claim("then a")]),
            new("WhenZzz", "", "ThenB", [Act("zzz"), Claim("then b")])];
        SubjectHeadings(Render(before)).Is().EqualTo(["## When zzz", "## When aaa"]);
        SubjectHeadings(Render([.. before, new("WhenZzz", "", "ThenC", [Act("zzz"), Claim("then c")])]))
            .Is().EqualTo(["## When zzz", "## When aaa"]);
    }
}
