using TSpec.Assert;
using TSpec.Internal.Document;

namespace TSpec.Test.Internal.Document;

public class WhenRenderDocument : Spec
{
    private static readonly SpecificationSubject _myHotel = new("MyHotel", "0.1.0");

    private static readonly SpecificationEntry _respondOk = new(
        "WhenGetVersion", "GivenNothing", "ThenRespondOk",
        "Using owned CreateClient\nWhen api.GetAsync(\"/version\")\nThen Result.StatusCode is HttpStatusCode.OK");

    private static string Render(params SpecificationEntry[] entries)
        => DocumentRenderer.Render(_myHotel, "MyHotel.Spec", entries);

    [Fact]
    public void GivenNoEntries_ThenRenderTheHeaderAlone()
        => Render().Is(
            "# MyHotel\n"
            + "\n"
            + "Version 0.1.0\n"
            + "\n"
            + "<!-- Generated by TSpec from MyHotel.Spec. Do not edit by hand. -->\n");

    [Fact]
    public void ThenRenderTheRequirementUnderItsSubject()
        => Render(_respondOk).Is(
            "# MyHotel\n"
            + "\n"
            + "Version 0.1.0\n"
            + "\n"
            + "<!-- Generated by TSpec from MyHotel.Spec. Do not edit by hand. -->\n"
            + "\n"
            + "## WhenGetVersion\n"
            + "\n"
            + "### GivenNothing.ThenRespondOk\n"
            + "\n"
            + "```\n"
            + "Using owned CreateClient\n"
            + "When api.GetAsync(\"/version\")\n"
            + "Then Result.StatusCode is HttpStatusCode.OK\n"
            + "```\n");

    [Fact]
    public void GivenNoBranch_ThenHeadTheRequirementByNameAlone()
        => Render(_respondOk with { Branch = "" }).Does().Contain("### ThenRespondOk\n");

    /// <summary>Two requirements of one subject share a single subject heading.</summary>
    [Fact]
    public void ThenGroupRequirementsBySubject()
    {
        var document = Render(_respondOk, _respondOk with { Requirement = "ThenReturnVersion" });
        document.Split("## WhenGetVersion").Length.Is(2);
        document.Does().Contain("### GivenNothing.ThenRespondOk").and.Contain("### GivenNothing.ThenReturnVersion");
    }

    [Fact]
    public void GivenEntriesOutOfOrder_ThenSortThem()
        => Render(
            _respondOk with { Requirement = "ThenB" },
            _respondOk with { Requirement = "ThenA" })
            .Does().Contain("### GivenNothing.ThenA\n\n```\nUsing owned CreateClient\nWhen api.GetAsync(\"/version\")\nThen Result.StatusCode is HttpStatusCode.OK\n```\n\n### GivenNothing.ThenB");

    /// <summary>A theory reports once per case; identical text must not repeat in the document.</summary>
    [Fact]
    public void GivenDuplicateEntries_ThenRenderOne()
        => Render(_respondOk, _respondOk).Is(Render(_respondOk));

    /// <summary>Specification text is built with Environment.NewLine, so it arrives CRLF on Windows.</summary>
    [Fact]
    public void GivenCrLfInTheSpecificationText_ThenNormaliseToLf()
        => Render(_respondOk with { Text = "When a\r\nThen b" })
            .Does().Contain("```\nWhen a\nThen b\n```").and.not.Contain("\r");
}
