using TSpec.Architecture;
using TSpec.Assert;
using TSpec.Internal.Document;
using TSpec.Internal.Document.RenderPipeline;
using TSpec.Internal.Specification;

namespace TSpec.Test.Architecture;

public class WhenRenderTheArchitectureDocument : Spec
{
    private static readonly SourceProjects _hotel = new(new()
    {
        ["Company.Hotel"] = ["Company.Hotel.Entry", "P:Scalar.AspNetCore"],
        ["Company.Hotel.Entry"] = ["Company.Hotel.Contract"],
        ["Company.Hotel.Contract"] = [],
        ["Company.Hotel.Spec"] = ["Company.Hotel", "P:TSpec", "P:xunit.v3"],
        ["Company.Hotel.Entry.Spec"] = ["Company.Hotel.Entry", "P:TSpec"],
    }, spec: "Company.Hotel.Architecture.Spec");

    private static readonly Dictionary<string, string> _noIndexes = [];

    [Fact]
    public void GivenAProjectHasASpecification_ThenLinkItsNodeToTheIndex()
        => ArchitectureRenderer.Render(_hotel, "Hotel.Architecture.Spec", [],
            new Dictionary<string, string> { ["Company.Hotel.Spec"] = "../Hotel.Spec/_specification/README.md" })
            .Does().Contain(
                "    Hotel_Spec -.-> Hotel\n"
                + "    click Hotel \"../Hotel.Spec/_specification/README.md\"\n"
                + "    classDef spec");

    [Fact]
    public void ThenTitleAndDrawTheProjectsUnderTheirRoot()
        => ArchitectureRenderer.Render(_hotel, "Hotel.Architecture.Spec", [], _noIndexes).Is(
            """
            # Hotel

            <!-- Generated by TSpec from Hotel.Architecture.Spec. Do not edit by hand. -->

            ```mermaid
            flowchart TD
                Hotel
                Contract
                Entry
                Entry_Spec["Entry.Spec"]:::spec
                Hotel_Spec["Hotel.Spec"]:::spec
                Hotel --> Entry
                Entry --> Contract
                Entry_Spec -.-> Entry
                Hotel_Spec -.-> Hotel
                classDef spec fill:none,stroke-dasharray:4 3,opacity:0.8
            ```

            """.NormalizeLineEndings());

    [Fact]
    public void GivenTests_ThenRenderThemBelowTheGraphAsAnyTestIsRendered()
        => ArchitectureRenderer.Render(_hotel, "Hotel.Architecture.Spec", [
            new("Layers", "", "InfraDeclaresNoInterface",
                [new([new SpecificationStep(StepLayout.Sentence) { Family = StepFamily.None, Body = "types of Infra is empty" }])],
                Namespace: "Hotel.Architecture.Spec")], _noIndexes)
            .Does().EndWith("```\n\n## Layers\n\n- **Infra declares no interface** — `Types of Infra is empty`\n");

    [Fact]
    public void GivenATestTablesWhatIsAllowed_ThenRenderTheTableUnderItsBullet()
        => ArchitectureRenderer.Render(_hotel, "Hotel.Architecture.Spec", [
            new("ProjectDependencies", "", "AreOnlyThese",
                [new([new SpecificationStep(StepLayout.Sentence) { Family = StepFamily.None, Body = "projects is within" }])],
                Namespace: "Hotel.Architecture.Spec",
                Table: new(["Project", "May reference", "May use"], [["Hotel", "Entry", "Scalar"]]))], _noIndexes)
            .Does().Contain(
                "- **Are only these** — `Projects is within`\n"
                + "\n"
                + "  | Project | May reference | May use |\n"
                + "  | ------- | ------------- | ------- |\n"
                + "  | Hotel   | Entry         | Scalar  |\n");

    [Fact]
    public void GivenAProjectReachesTSpecThroughAnother_ThenDrawItAsASpecProject()
        => ArchitectureRenderer.Render(new(new()
        {
            ["Hotel"] = [],
            ["Hotel.Spec"] = ["Hotel", "Hotel.Testing"],
            ["Hotel.Testing"] = ["P:TSpec"],
        }), "Hotel.Architecture.Spec", [], _noIndexes).Does().Contain("    Hotel_Spec[\"Hotel.Spec\"]:::spec\n");

    [Fact]
    public void GivenNoRoot_ThenTitleItAsTheSpecProject()
        => ArchitectureRenderer.Render(new(new() { ["Hotel"] = [], ["Tools"] = [] }), "Hotel.Architecture.Spec", [], _noIndexes)
            .Does().StartWith("# Hotel Architecture Spec\n");
}
