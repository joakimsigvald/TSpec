using TSpec.Assert;
using TSpec.Extensibility;
using TSpec.Internal.Document;
using TSpec.Internal.Specification;

namespace TSpec.Test.Extensibility;

/// <summary>
/// A page an extension package writes: TSpec titles it and lays out the tests; the package states what goes
/// between them.
/// </summary>
public class WhenWriteAPage : Spec
{
    private static readonly SpecificationEntry _layers = new("Layers", "", "InfraDeclaresNoInterface",
        [new([new SpecificationStep(StepLayout.Sentence) { Family = StepFamily.None, Body = "types of Infra is empty" }])],
        Namespace: "Hotel.Architecture.Spec");

    [Fact]
    public void ThenTitleItByItsSubjectInWords_AndSayItIsGenerated()
        => SpecificationPage.Render("MyHotel", "Hotel.Architecture.Spec", header: "", [], sourceRoot: null)
            .Is("# My Hotel\n\n<!-- Generated by TSpec from Hotel.Architecture.Spec. Do not edit by hand. -->\n");

    [Fact]
    public void ThenStateTheHeaderBetweenTheTitleAndTheTests()
        => SpecificationPage.Render("MyHotel", "Hotel.Architecture.Spec", header: "Above the tests.", [_layers], sourceRoot: null)
            .Does().EndWith(
                "-->\n\nAbove the tests.\n\n## Layers\n\n- **Infra declares no interface** — `Types of Infra is empty`\n");

    [Fact]
    public void GivenAnAssemblyWithNoSpecificationIndex_ThenFindNone()
        => Build.TryFindSpecificationIndex("TSpec.Test", out _).Is().False();
}
